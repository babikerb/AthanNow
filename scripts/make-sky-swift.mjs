// Generates widgets/SkyScene.swift from the app's sky illustration, so the widget's sky is the
// same drawing as Home's (src/components/sky/palettes.ts + SkyIllustration.tsx).
//   node scripts/make-sky-swift.mjs          write
//   node scripts/make-sky-swift.mjs --check  fail if the Swift file is out of date
import fs from 'node:fs';
import path from 'node:path';
import ts from 'typescript';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')), '..');
const palettesSrc = fs.readFileSync(path.join(root, 'src/components/sky/palettes.ts'), 'utf8');
const illustration = fs.readFileSync(path.join(root, 'src/components/sky/SkyIllustration.tsx'), 'utf8');

const js = ts.transpileModule(palettesSrc, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText;
const mod = {};
new Function('exports', js)(mod);
const { SCENES, STAR_FIELD, INK } = mod;

const constPath = (name) => illustration.match(new RegExp(`const ${name} = '([^']+)'`))[1];
const skyline = illustration
  .match(/const SKYLINE = \[([\s\S]*?)\]\.join/)[1]
  .match(/'([^']+)'/g)
  .map((s) => s.slice(1, -1))
  .join(' ');

const n = (v) => (Number.isInteger(v) ? `${v}` : `${+v.toFixed(3)}`);
const pt = (x, y) => `CGPoint(x: ${n(x)}, y: ${n(y)})`;

/** SVG path data (M C L H V Z, absolute) -> Swift Path statements. */
function swiftPath(d) {
  const tokens = d.match(/[MCLHVZ]|-?\d*\.?\d+/g);
  const out = [];
  let i = 0;
  let cmd = '';
  let cx = 0;
  let cy = 0;
  const num = () => parseFloat(tokens[i++]);
  while (i < tokens.length) {
    if (/[MCLHVZ]/.test(tokens[i])) cmd = tokens[i++];
    switch (cmd) {
      case 'M': cx = num(); cy = num(); out.push(`p.move(to: ${pt(cx, cy)})`); cmd = 'L'; break;
      case 'L': cx = num(); cy = num(); out.push(`p.addLine(to: ${pt(cx, cy)})`); break;
      case 'H': cx = num(); out.push(`p.addLine(to: ${pt(cx, cy)})`); break;
      case 'V': cy = num(); out.push(`p.addLine(to: ${pt(cx, cy)})`); break;
      case 'C': {
        const [x1, y1, x2, y2, x, y] = [num(), num(), num(), num(), num(), num()];
        out.push(`p.addCurve(to: ${pt(x, y)}, control1: ${pt(x1, y1)}, control2: ${pt(x2, y2)})`);
        cx = x; cy = y;
        break;
      }
      case 'Z': out.push('p.closeSubpath()'); cmd = ''; break;
      default: throw new Error(`Unsupported path command "${cmd}" in ${d}`);
    }
  }
  return out.map((l) => `    ${l}`).join('\n');
}

const hex = (c) => `Color(dtHex: 0x${c.replace('#', '').toUpperCase()})`;

const periods = Object.keys(SCENES);
const sceneEntries = periods
  .map((k) => {
    const s = SCENES[k];
    const b = s.body;
    const body =
      b.kind === 'sun'
        ? `.sun(x: ${n(b.x)}, y: ${n(b.y)}, r: ${n(b.r)}, color: ${hex(b.color)})`
        : `.crescent(x: ${n(b.x)}, y: ${n(b.y)}, r: ${n(b.r)}, color: ${hex(b.color)}, waning: ${!!b.waning})`;
    return `    "${k}": SkyScenePalette(
      sky: [${s.sky.map(hex).join(', ')}],
      ridges: [${s.ridges.map(hex).join(', ')}],
      body: ${body},
      stars: ${s.stars},
      starOpacity: ${n(s.starOpacity)},
      clouds: ${s.clouds}
    ),`;
  })
  .join('\n');

const stars = STAR_FIELD.map((s) => `  (${n(s.x)}, ${n(s.y)}, ${n(s.r)}, ${n(s.o)}),`).join('\n');

const swift = `// GENERATED by scripts/make-sky-swift.mjs from src/components/sky. Do not edit by hand.
// The widget's sky is the same illustration as the app's Home screen.

import SwiftUI

extension Color {
  init(dtHex v: UInt32) {
    self.init(.sRGB, red: Double((v >> 16) & 0xFF) / 255, green: Double((v >> 8) & 0xFF) / 255, blue: Double(v & 0xFF) / 255, opacity: 1)
  }
}

let SKY_INK = ${hex(INK)}

enum SkyBody {
  case sun(x: CGFloat, y: CGFloat, r: CGFloat, color: Color)
  case crescent(x: CGFloat, y: CGFloat, r: CGFloat, color: Color, waning: Bool)
}

struct SkyScenePalette {
  let sky: [Color]
  let ridges: [Color]
  let body: SkyBody
  let stars: Int
  let starOpacity: Double
  let clouds: Bool
}

let SKY_SCENES: [String: SkyScenePalette] = [
${sceneEntries}
]

private let STAR_FIELD: [(CGFloat, CGFloat, CGFloat, Double)] = [
${stars}
]

private func ridgeFar() -> Path {
  var p = Path()
${swiftPath(constPath('RIDGE_FAR'))}
  return p
}

private func ridgeMid() -> Path {
  var p = Path()
${swiftPath(constPath('RIDGE_MID'))}
  return p
}

private func ridgeNear() -> Path {
  var p = Path()
${swiftPath(constPath('RIDGE_NEAR'))}
  return p
}

private func skyline() -> Path {
  var p = Path()
${swiftPath(skyline)}
  return p
}

/// A cumulus: flat base plus uneven puffs, as one path so overlaps don't darken. (x, y) = left end of the base.
private func cloud(_ x: CGFloat, _ y: CGFloat, _ w: CGFloat, _ h: CGFloat) -> Path {
  var p = Path()
  p.addRoundedRect(in: CGRect(x: x, y: y - h * 0.34, width: w, height: h * 0.34), cornerSize: CGSize(width: h * 0.17, height: h * 0.17))
  let puffs: [(CGFloat, CGFloat, CGFloat)] = [(0.18, 0.34, 0.3), (0.4, 0.62, 0.42), (0.62, 0.6, 0.38), (0.82, 0.36, 0.26)]
  for (fx, fy, fr) in puffs {
    let r = h * fr * 1.25
    p.addEllipse(in: CGRect(x: x + w * fx - r, y: y - h * fy - r * 0.8, width: r * 2, height: r * 1.8))
  }
  return p
}

/// The illustration, authored on a 390 x 340 box and drawn like SVG \`xMidYMax slice\`:
/// it fills the frame, stays anchored to the bottom edge and crops sky (never ground).
struct SkySceneView: View {
  let period: String
  /// Set when a label sits over the top-left of the scene: a sun or moon there moves to the right side.
  var labelTopLeft: Bool = false

  var body: some View {
    GeometryReader { geo in
      let scene = SKY_SCENES[period] ?? SKY_SCENES["night"]!
      let s = max(geo.size.width / 390, geo.size.height / 340)
      let t = CGAffineTransform(translationX: (geo.size.width - 390 * s) / 2, y: geo.size.height - 340 * s).scaledBy(x: s, y: s)
      ZStack {
        scene.sky.first!
        LinearGradient(colors: scene.sky, startPoint: .top, endPoint: .bottom)
          .frame(width: 390 * s, height: 340 * s)
          .position(x: geo.size.width / 2, y: geo.size.height - 170 * s)
        if scene.stars > 0 {
          ForEach(0..<scene.stars, id: \\.self) { i in
            let st = STAR_FIELD[i]
            Path(ellipseIn: CGRect(x: st.0 - st.2, y: st.1 - st.2, width: st.2 * 2, height: st.2 * 2))
              .applying(t)
              .fill(Color.white.opacity(st.3 * scene.starOpacity))
          }
        }
        if scene.clouds {
          let tint = period == "sunrise" ? Color(dtHex: 0xF1C7B4) : Color.white
          let alpha = period == "sunrise" ? 0.3 : 0.42
          cloud(52, 156, 120, 26).applying(t).fill(tint.opacity(alpha))
          cloud(70, 140, 50, 16).applying(t).fill(Color.white.opacity(alpha * 0.55))
          cloud(236, 180, 110, 22).applying(t).fill(tint.opacity(alpha * 0.8))
        }
        bodyShape(placed(scene.body, visibleTop: 340 - geo.size.height / s), t)
        if scene.ridges.count == 3 {
          ridgeFar().applying(t).fill(scene.ridges[0])
          ridgeMid().applying(t).fill(scene.ridges[1])
          ridgeNear().applying(t).fill(scene.ridges[2])
        }
        skyline().applying(t).fill(SKY_INK)
      }
    }
  }

  /// Keeps the body inside the visible part of the band and clear of a top-left label.
  private func placed(_ b: SkyBody, visibleTop: CGFloat) -> SkyBody {
    func fit(_ x: CGFloat, _ y: CGFloat, _ r: CGFloat) -> (CGFloat, CGFloat) {
      let nx = labelTopLeft && x < 195 ? 390 - x : x
      guard y < 200 else { return (nx, y) }
      return (nx, min(max(y, visibleTop + r + 6), 200 - r * 0.3))
    }
    switch b {
    case let .sun(x, y, r, color):
      let p = fit(x, y, r)
      return .sun(x: p.0, y: p.1, r: r, color: color)
    case let .crescent(x, y, r, color, waning):
      let p = fit(x, y, r)
      return .crescent(x: p.0, y: p.1, r: r, color: color, waning: waning)
    }
  }

  @ViewBuilder
  private func bodyShape(_ b: SkyBody, _ t: CGAffineTransform) -> some View {
    switch b {
    case let .sun(x, y, r, color):
      Path(ellipseIn: CGRect(x: x - r, y: y - r, width: r * 2, height: r * 2)).applying(t).fill(color)
    case let .crescent(x, y, r, color, waning):
      let disc = CGPath(ellipseIn: CGRect(x: x - r, y: y - r, width: r * 2, height: r * 2), transform: nil)
      let ox = x + (waning ? 1 : -1) * r * 0.58
      let oy = y - r * 0.18
      let rr = r * 1.02
      let shadow = CGPath(ellipseIn: CGRect(x: ox - rr, y: oy - rr, width: rr * 2, height: rr * 2), transform: nil)
      Path(disc.subtracting(shadow)).applying(t).fill(color)
    }
  }
}
`;

const target = path.join(root, 'widgets/SkyScene.swift');
if (process.argv.includes('--check')) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
  if (current.replace(/\r\n/g, '\n') !== swift) {
    console.error('widgets/SkyScene.swift is out of date. Run: node scripts/make-sky-swift.mjs');
    process.exit(1);
  }
  console.log('widgets/SkyScene.swift is up to date.');
} else {
  fs.writeFileSync(target, swift);
  console.log('Wrote widgets/SkyScene.swift');
}
