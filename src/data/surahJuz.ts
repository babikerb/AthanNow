/** "Juz 1" or "Juz 1 to 3". */
export function juzLabel(id: number): string {
  const j = SURAH_JUZ[id - 1] ?? [];
  return j.length > 1 ? `Juz ${j[0]} to ${j[j.length - 1]}` : `Juz ${j[0]}`;
}
